def full_name(guest):

    first_name = guest.get(
        "first_name",
        guest.get(
            "name",
            ""
        )
    )

    last_name = guest.get(
        "last_name",
        guest.get(
            "surname",
            ""
        )
    )

    return f"{first_name} {last_name}".strip()


def get_guest(
    guest_id
):

    return guests.get(
        guest_id
    )


def all_guests():

    return guests


def guest_count():

    return len(
        guests
    )


def guests_by_tier(
    tier
):

    tier = str(
        tier or ""
    ).strip().lower()

    return {
        guest_id: guest

        for guest_id, guest
        in guests.items()

        if str(
            guest.get(
                "tier",
                ""
            )
        ).lower() == tier
    }


def guests_by_language(
    language
):

    language = str(
        language or ""
    ).strip().upper()

    return {
        guest_id: guest

        for guest_id, guest
        in guests.items()

        if str(
            guest.get(
                "language",
                ""
            )
        ).upper() == language
    }


def marketing_eligible_guests():

    return {
        guest_id: guest

        for guest_id, guest
        in guests.items()

        if guest.get(
            "marketing_allowed",
            False
        )

        and not guest.get(
            "self_excluded",
            False
        )

        and not guest.get(
            "blocked",
            False
        )

        and not guest.get(
            "do_not_contact",
            False
        )
    }